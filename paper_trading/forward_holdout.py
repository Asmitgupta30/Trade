r"""Pre-registered forward holdout for confidence-gate parameters (Section E).

The gate=0.60 hypothesis was generated by sweeping gates on the deep dataset's
most recent OOS windows — the same windows Section B validated on. NO backward
holdout exists (data ends at the present). Per the phase's new methodology
rule, a sweep result is a HYPOTHESIS until it replicates on data that did not
exist when the sweep ran.

This module owns that test:
  * arms are FIXED at registration time (default 0.55 vs candidate 0.60);
    never edited, never extended with better-performing values found later
  * accrual starts at the first live trading day AFTER registration
  * verdict logic is binary and mechanical:
      replicate      : candidate-arm Sharpe > 0 AND candidate hit-rate > default
                       arm hit-rate, once BOTH arms have >= min_n outcomes
      not replicated : both arms >= min_n and the condition fails
      pending        : deadline not reached, insufficient n
      inconclusive   : deadline passed without enough n in one/both arms
  * run_challenger_cycle registers any recommended gate here automatically;
    the recommendation stays 'pending' until this test rules on it
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
REGISTRY_PATH = ROOT / "var" / "status" / "forward_holdout_registry.json"
REPORT_PATH = ROOT / "var" / "reports" / "section_e_held_out_gate_check.md"
MIN_N_PER_ARM = 40
DEADLINE_WEEKS = 8


@dataclass
class HoldoutArm:
    gate: float
    description: str


@dataclass
class HoldoutRegistration:
    candidate_gate: float
    default_gate: float
    registered_at: str
    accrual_start: str                 # first live trading day (IST)
    min_n_per_arm: int = MIN_N_PER_ARM
    deadline_weeks: int = DEADLINE_WEEKS
    status: str = "pending"            # pending | confirmed | not_replicated | inconclusive
    resolved_at: str | None = None
    evidence: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return asdict(self)


def load_registrations() -> list[dict]:
    if not REGISTRY_PATH.exists():
        return []
    try:
        return json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    except Exception:
        return []


def save_registrations(regs: list[dict]) -> None:
    REGISTRY_PATH.parent.mkdir(parents=True, exist_ok=True)
    REGISTRY_PATH.write_text(json.dumps(regs, indent=2), encoding="utf-8")


def register(candidate_gate: float, default_gate: float,
             accrual_start: str,
             source: str = "section_e") -> dict:
    """Idempotent: one live registration per (candidate, default) pair."""
    regs = load_registrations()
    for r in regs:
        if (r["candidate_gate"] == candidate_gate
                and r["status"] == "pending"):
            return r
    reg = HoldoutRegistration(
        candidate_gate=candidate_gate, default_gate=default_gate,
        registered_at=datetime.now(timezone.utc).isoformat(),
        accrual_start=accrual_start).__dict__
    reg["source"] = source
    regs.append(reg)
    save_registrations(regs)
    return reg


def _next_monday_iso(now: datetime | None = None) -> str:
    import zoneinfo

    ist = zoneinfo.ZoneInfo("Asia/Kolkata")
    from common.timeutils import is_trading_day
    d = (now or datetime.now(ist)).date()
    while True:
        d = d.fromordinal(d.toordinal() + 1)
        if is_trading_day(d):
            return d.isoformat()


# ---------------- evaluation ----------------
def _arm_stats(suggestions: list[dict], gate: float, start_iso: str) -> dict:
    """Outcomes for closed BUY/STRONG_BUY suggestions with confidence>=gate
    created on/after accrual start. Net-of-cost per-trade returns."""
    rows = []
    for s in suggestions:
        if s.get("action") not in ("BUY", "STRONG_BUY"):
            continue
        conf = s.get("confidence")
        if conf is None or conf < gate:
            continue
        ts = s.get("created_ts") or ""
        if ts[:10] < start_iso[:10]:
            continue
        ret = s.get("realized_return_pct")
        direction_ok = s.get("direction_ok")
        if ret is None:
            continue
        rows.append({"return_pct": float(ret),
                     "direction_ok": bool(direction_ok)})
    n = len(rows)
    out = {"n": n, "gate": gate}
    if n == 0:
        out.update({"mean_net_ret_pct": None, "hit_rate": None, "sharpe": None})
        return out
    rets = np.array([r["return_pct"] for r in rows]) / 100.0
    sd = rets.std(ddof=1)
    out["mean_net_ret_pct"] = round(float(rets.mean() * 100), 4)
    out["hit_rate"] = round(float(np.mean([r["direction_ok"] for r in rows])), 4)
    out["sharpe"] = (round(float(rets.mean() / sd * np.sqrt(252)), 3)
                     if sd and sd > 0 else 0.0)
    return out


def evaluate_registration(reg: dict, suggestions: list[dict],
                          now: datetime | None = None) -> dict:
    """Mechanical verdict. `suggestions` come from the paper store joined with
    closed-position outcomes (see PaperEngine helpers)."""
    start = reg["accrual_start"]
    min_n = reg.get("min_n_per_arm", MIN_N_PER_ARM)
    arm_c = _arm_stats(suggestions, reg["candidate_gate"], start)
    arm_d = _arm_stats(suggestions, reg["default_gate"], start)
    result = {
        "candidate_arm": arm_c,
        "default_arm": arm_d,
    }
    reg.setdefault("evidence", {})
    reg["evidence"].update(result)

    registered = datetime.fromisoformat(reg["registered_at"])
    now = now or datetime.now(timezone.utc)
    weeks_elapsed = (now - registered).total_seconds() / (86400 * 7)

    if arm_c["n"] >= min_n and arm_d["n"] >= min_n:
        # Replication = positive expectancy AND higher hit-rate than default.
        # Expectancy sign (mean net return) is the primary signal because a
        # low-variance winning arm can have an undefined/zero Sharpe.
        replicate = (
            arm_c["mean_net_ret_pct"] is not None
            and arm_c["mean_net_ret_pct"] > 0
            and arm_c["hit_rate"] is not None
            and arm_d["hit_rate"] is not None
            and arm_c["hit_rate"] > arm_d["hit_rate"])
        reg["status"] = "confirmed" if replicate else "not_replicated"
        reg["resolved_at"] = datetime.now(timezone.utc).isoformat()
    elif weeks_elapsed >= reg.get("deadline_weeks", DEADLINE_WEEKS):
        reg["status"] = "inconclusive-too-small-sample"
        reg["resolved_at"] = datetime.now(timezone.utc).isoformat()
    else:
        reg["status"] = "pending"
    result["status"] = reg["status"]
    result["weeks_elapsed"] = round(weeks_elapsed, 2)
    return result


def update_all_registrations(suggestions: list[dict]) -> list[dict]:
    regs = load_registrations()
    results = []
    for r in regs:
        if r["status"] == "pending":
            results.append(evaluate_registration(r, suggestions))
        else:
            results.append(r.get("evidence", {}))
    save_registrations(regs)
    return results
